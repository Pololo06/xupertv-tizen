#!/usr/bin/env node
/*
 * Genera service/index.js a partir de xuper-relay-service.js.
 * Uso: node tools/build-standalone-service.js
 */
"use strict";

var fs = require("fs");
var path = require("path");

var root = path.resolve(__dirname, "..");
var bundlePath = path.join(root, "xuper-relay-service.js");
var outDir = path.join(root, "service");
var outPath = path.join(outDir, "index.js");

var bundle = fs.readFileSync(bundlePath, "utf8");
var pkgVersion = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).version;
bundle = bundle.replace(
  /("name":\s*"xupetv-relay",\s*"version":\s*")[^"]+(")/,
  "$1" + pkgVersion + "$2"
);

var out = [
  '"use strict";',
  "/*",
  " * XuperTV standalone relay service for Tizen.",
  " * Generated by tools/build-standalone-service.js. Do not edit by hand.",
  " */",
  "module.exports.onStart = function () {",
  '  process.env.XUPER_API_PORT = "8915";',
  '  process.env.XUPER_PROXY_PORT = "8795";',
  '  process.env.XUPER_RELAY_PORT = "8790";',
  '  process.env.XUPER_PUBLIC_HOST = "127.0.0.1";',
  '  process.env.XUPER_BIND_HOST = "127.0.0.1";',
  '  process.env.XUPER_EMBEDDED = "1";',
  '  process.env.XUPER_NO_FFMPEG = "1";',
  '  process.env.XUPER_FFMPEG = "/nonexistent/xuper-ffmpeg";',
  "",
  bundle,
  "};",
  "",
  "module.exports.onStop = function () {",
  "  // Tizen termina el proceso del servicio; no hace falta process.exit().",
  "};",
  ""
].join("\n");

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, out);
console.log("[+] Servicio standalone: " + outPath + " (" + Math.round(out.length / 1024) + " KB)");
